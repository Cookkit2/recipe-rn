const fs = require("fs");
const os = require("os");
const path = require("path");
const plist = require("@expo/plist").default;
const xcode = require("xcode");
const { customizeExtension, ensureShareExtensionDependency } = require("../withRecipeSharing");

it("makes the share extension discoverable for signing without duplicating its target dependency", () => {
  const project = xcode.project(
    path.resolve(__dirname, "../../ios/Cookkit.xcodeproj/project.pbxproj")
  );
  project.parseSync();
  const { uuid, firstTarget: application } = project.getFirstTarget();
  const extensionId = Object.keys(project.pbxNativeTargetSection()).find(
    (key) => project.pbxNativeTargetSection()[key]?.name === '"expo-sharing-extension"'
  );
  expect(extensionId).toBeDefined();
  // Reproduce the dependency-free target generated by the SDK 58 sharing plugin.
  application.dependencies = [];
  ensureShareExtensionDependency(project);
  const dependency =
    project.hash.project.objects.PBXTargetDependency[application.dependencies[0].value];
  expect(dependency.target).toBe(extensionId);
  expect(project.pbxNativeTargetSection()[uuid]).toBe(application);
  const generated = project.writeSync();
  ensureShareExtensionDependency(project);
  expect(project.writeSync()).toBe(generated);
});

it("preserves captions and the friendly name when generating the real SDK 58 extension", () => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), "cookkit-sharing-test-"));
  try {
    const target = path.join(root, "expo-sharing-extension");
    fs.mkdirSync(target);
    const packageRoot = path.dirname(require.resolve("expo-sharing/package.json"));
    const controller = path.join(target, "ShareIntoViewController.swift");
    fs.copyFileSync(
      path.join(packageRoot, "plugin/template-files/ios/ShareIntoViewController.swift"),
      controller
    );
    fs.writeFileSync(
      path.join(target, "Info.plist"),
      plist.build({ CFBundleDisplayName: "$(PRODUCT_NAME)" })
    );
    customizeExtension(root);
    const generated = fs.readFileSync(controller, "utf8");
    expect(generated).toContain("item.attributedContentText?.string");
    expect(generated).toContain("let caption = await handleText(provider)");
    expect(
      plist.parse(fs.readFileSync(path.join(target, "Info.plist"), "utf8")).CFBundleDisplayName
    ).toBe("Cookkit Import");
    customizeExtension(root);
    expect(fs.readFileSync(controller, "utf8")).toBe(generated);
  } finally {
    fs.rmSync(root, { recursive: true, force: true });
  }
});
